import "dotenv/config";
import { randomUUID } from "node:crypto";
import { test, expect, type Page } from "@playwright/test";
import pg from "pg";
import ExcelJS from "exceljs";
import { E2E_ADMIN_EMAIL, E2E_ADMIN_PASSWORD } from "./fixtures";
test.use({ actionTimeout: 15000 });

async function adminLogin(page: Page) {
  await page.goto("/login");
  await page.getByLabel("이메일").fill(E2E_ADMIN_EMAIL);
  await page.getByLabel("비밀번호", { exact: true }).fill(E2E_ADMIN_PASSWORD);
  await page.getByRole("button", { name: "로그인", exact: true }).click();
  await expect(page).toHaveURL(/\/admin$/);
}

test("order workflow, snapshots, concurrent actions, Excel and USER boundaries", async ({ page }) => {
  test.setTimeout(180000);
  const prefix = `E2E-ORDER-${randomUUID().slice(0, 8).toUpperCase()}`;
  const db = new pg.Client({ connectionString: process.env.DATABASE_URL });
  await db.connect();
  const touched = new Set<string>();
  const headers = { origin: "http://127.0.0.1:3002" };
  const post = (path: string, data: unknown) => page.request.post(path, { headers, data });
  const patch = (path: string, data: unknown) => page.request.patch(path, { headers, data });
  const del = (path: string, data: unknown) => page.request.delete(path, { headers, data });
  const getOrder = async (id: string) => (await (await page.request.get(`/api/orders/${id}`)).json()).item;
  try {
    expect((await page.request.get("/api/orders")).status()).toBe(401);
    expect((await page.request.get("/api/orders/export")).status()).toBe(401);
    await adminLogin(page);
    const customerResponse = await post("/api/customers", { code: `${prefix}-C`, name: `${prefix} 거래처`, defaultAddress: "가상 배송지" });
    expect(customerResponse.status()).toBe(201);
    const customer = (await customerResponse.json()).item; touched.add(customer.id);
    const products = [];
    for (const suffix of ["1", "2"]) {
      const response = await post("/api/products", { code: `${prefix}-P${suffix}`, name: `=${prefix}-${suffix}`, unit: "EA", defaultUnitPrice: suffix === "1" ? "10.25" : "5" });
      expect(response.status()).toBe(201); const product = (await response.json()).item; products.push(product); touched.add(product.id);
    }
    await page.goto("/admin/orders/new");
    await page.getByLabel("거래처", { exact: true }).selectOption(customer.id);
    await page.getByLabel("품목 1", { exact: true }).selectOption(products[0].id);
    await page.getByLabel("수량 1", { exact: true }).fill("2.5");
    await page.getByRole("button", { name: "품목 추가" }).click();
    await page.getByLabel("품목 2", { exact: true }).selectOption(products[1].id);
    await expect(page.getByRole("status")).toContainText("30.63");
    await page.getByRole("button", { name: "주문 접수", exact: true }).click();
    await expect(page).toHaveURL(/\/admin\/orders\/(?!new)[^/]+$/);
    const id = new URL(page.url()).pathname.split("/").at(-1)!; touched.add(id);
    let order = await getOrder(id);
    expect(order.totalAmount).toBe("30.63");
    expect(order.orderNo).toMatch(/^ORD-\d{8}-\d{4,}$/);
    expect((await post(`/api/orders/${id}/ship`, { version: order.version })).status()).toBe(409);
    expect((await patch(`/api/orders/${id}`, { version: order.version, status: "SHIPPED" })).status()).toBe(400);
    expect((await page.request.post(`/api/orders/${id}/confirm`, { headers: { origin: "https://untrusted.invalid" }, data: { version: order.version } })).status()).toBe(403);
    // Changing masters must not rewrite existing order snapshots.
    expect((await patch(`/api/customers/${customer.id}`, { name: "변경된 가상 거래처" })).status()).toBe(200);
    expect((await patch(`/api/products/${products[0].id}`, { name: "변경된 가상 품목" })).status()).toBe(200);
    expect((await getOrder(id)).customerNameSnapshot).toBe(customer.name);
    expect((await getOrder(id)).items[0].productNameSnapshot).toBe(products[0].name);
    await page.getByRole("button", { name: "주문 확인", exact: true }).click();
    await page.getByRole("button", { name: "처리 실행" }).click();
    await expect.poll(async () => (await getOrder(id)).status).toBe("CONFIRMED");
    await page.reload();
    await page.getByLabel("처리 사유", { exact: false }).fill("E2E 수정 필요");
    await page.getByRole("button", { name: "확인 취소", exact: true }).click();
    await page.getByRole("button", { name: "처리 실행" }).click();
    await expect.poll(async () => (await getOrder(id)).status).toBe("RECEIVED");
    order = await getOrder(id);
    const firstConfirmedAt = order.firstConfirmedAt;
    expect((await del(`/api/orders/${id}`, { version: order.version, reason: "삭제 시도" })).status()).toBe(409);
    await page.reload();
    await page.locator("form:visible").getByLabel("주문 메모", { exact: true }).fill("E2E 수정");
    await page.getByRole("button", { name: "주문 수정 저장" }).click();
    await expect.poll(async () => (await getOrder(id)).version).toBe(order.version + 1);
    order = await getOrder(id);
    expect(order.items[0].productNameSnapshot).toBe(products[0].name);
    const confirmations = await Promise.all([post(`/api/orders/${id}/confirm`, { version: order.version }), post(`/api/orders/${id}/confirm`, { version: order.version })]);
    expect(confirmations.map(r => r.status()).sort()).toEqual([200, 409]);
    order = await getOrder(id); expect(order.firstConfirmedAt).toBe(firstConfirmedAt);
    await page.reload();
    await page.getByLabel("운송사", { exact: true }).fill("E2E 가상 운송사");
    await page.getByLabel("송장번호", { exact: true }).fill("E2E-NOT-REAL");
    await page.getByRole("button", { name: "전체 출고", exact: true }).click();
    await page.getByRole("button", { name: "처리 실행" }).click();
    await expect.poll(async () => (await getOrder(id)).status).toBe("SHIPPED");
    order = await getOrder(id);
    expect((await post(`/api/orders/${id}/ship`, { version: order.version })).status()).toBe(409);
    expect((await del(`/api/customers/${customer.id}`, { reason: "사용 이력" })).status()).toBe(409);
    expect((await del(`/api/products/${products[0].id}`, { reason: "사용 이력" })).status()).toBe(409);
    const audit = await db.query('SELECT action FROM "AuditLog" WHERE "targetId"=$1 ORDER BY "createdAt"', [id]);
    expect(audit.rows.map(x => x.action)).toEqual(["ORDER_CREATED", "ORDER_CONFIRMED", "ORDER_CONFIRMATION_REVERTED", "ORDER_UPDATED", "ORDER_CONFIRMED", "ORDER_SHIPPED"]);
    await page.goto(`/admin/orders?q=${order.orderNo}&status=SHIPPED`);
    await expect(page.getByRole("link", { name: order.orderNo })).toBeVisible();
    const downloadPromise = page.waitForEvent("download");
    await page.getByRole("button", { name: "Excel 다운로드" }).click();
    const download = await downloadPromise;
    expect(download.suggestedFilename()).toBe("orders.xlsx");
    const stream = await download.createReadStream();
    const chunks = []; for await (const chunk of stream!) chunks.push(chunk);
    const workbook = new ExcelJS.Workbook();
    await workbook.xlsx.load(Buffer.concat(chunks) as unknown as Parameters<typeof workbook.xlsx.load>[0]);
    expect(workbook.worksheets[0].rowCount).toBe(3);
    expect(workbook.worksheets[0].getCell("G2").value).toBe(`'${products[0].name}`);
    expect(workbook.worksheets[0].getCell("L2").value).toBe(25.63);
    await page.goto("/admin/operations");
    await expect(page.getByRole("heading", { name: "업무 현황", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "로그아웃" }).click();
    await expect(page).toHaveURL(/\/login$/);
    await page.getByRole("button", { name: "가입 없이 데모 체험하기" }).click();
    await expect(page).toHaveURL(/\/admin\/tasks$/);
    const input = { customerId: customer.id, shippingAddress: "가상", items: [{ productId: products[1].id, quantity: "1", unitPrice: "5" }] };
    // Concurrent creation uses unique per-day counter values.
    const responses = await Promise.all([post("/api/orders", input), post("/api/orders", input)]);
    expect(responses.map(r => r.status())).toEqual([201, 201]);
    const created = await Promise.all(responses.map(async r => (await r.json()).item));
    for (const item of created) touched.add(item.id);
    expect(created[0].orderNo).not.toBe(created[1].orderNo);
    const userOrder = created[0];
    expect((await patch(`/api/orders/${userOrder.id}`, { ...input, version: 1, memo: "USER 수정" })).status()).toBe(200);
    expect((await post(`/api/orders/${userOrder.id}/confirm`, { version: 2 })).status()).toBe(200);
    expect((await post(`/api/orders/${userOrder.id}/revert-confirmation`, { version: 3, reason: "우회" })).status()).toBe(403);
    expect((await post(`/api/orders/${userOrder.id}/cancel`, { version: 3, reason: "우회" })).status()).toBe(403);
    expect((await del(`/api/orders/${userOrder.id}`, { version: 3, reason: "우회" })).status()).toBe(403);
    const shipping = await Promise.all([post(`/api/orders/${userOrder.id}/ship`, { version: 3 }), post(`/api/orders/${userOrder.id}/ship`, { version: 3 })]);
    expect(shipping.map(r => r.status()).sort()).toEqual([200, 409]);
    expect((await db.query('SELECT count(*)::int AS n FROM "Shipment" WHERE "orderId"=$1', [userOrder.id])).rows[0].n).toBe(1);
    expect((await post(`/api/orders/${created[1].id}/cancel`, { version: 1, reason: "" })).status()).toBe(400);
    expect((await post(`/api/orders/${created[1].id}/cancel`, { version: 1, reason: "E2E 접수 취소" })).status()).toBe(200);
    expect((await page.request.get(`/api/orders/export?customerId=${customer.id}`)).status()).toBe(200);
    expect((await post("/api/orders", { ...input, totalAmount: "0" })).status()).toBe(400);
    await page.goto("/admin/orders");
    await page.getByRole("button", { name: "로그아웃" }).click();
    await expect(page).toHaveURL(/\/login$/);
    await adminLogin(page);
    // Inactive masters cannot be used for a new order.
    expect((await patch(`/api/products/${products[1].id}`, { isActive: false })).status()).toBe(200);
    expect((await post("/api/orders", input)).status()).toBe(400);
    expect((await patch(`/api/products/${products[1].id}`, { isActive: true })).status()).toBe(200);
    const draft = (await (await post("/api/orders", input)).json()).item; touched.add(draft.id);
    expect((await del(`/api/orders/${draft.id}`, { version: 1, reason: "E2E 오입력" })).status()).toBe(204);
    expect((await page.request.get(`/api/orders/${draft.id}`)).status()).toBe(404);
    expect((await db.query('SELECT metadata FROM "AuditLog" WHERE "targetId"=$1 AND action=\'ORDER_DELETED\'', [draft.id])).rows[0].metadata.reason).toBe("E2E 오입력");
    const singleCustomer = (await (await post("/api/customers", { code: `${prefix}-C-ONLY`, name: "가상 이력 전용" })).json()).item;
    const singleProduct = (await (await post("/api/products", { code: `${prefix}-P-ONLY`, name: "가상 이력 전용", unit: "EA" })).json()).item;
    touched.add(singleCustomer.id); touched.add(singleProduct.id);
    const onlyInput = { customerId: singleCustomer.id, shippingAddress: "가상", items: [{ productId: singleProduct.id, quantity: "1", unitPrice: "1" }] };
    expect((await post("/api/orders", { ...onlyInput, items: [{ productId: singleProduct.id, quantity: "99999999999.999", unitPrice: "999999999999.99" }] })).status()).toBe(400);
    expect((await db.query('SELECT "hasOrderHistory" FROM "Customer" WHERE id=$1', [singleCustomer.id])).rows[0].hasOrderHistory).toBe(false);
    const onlyOrder = (await (await post("/api/orders", onlyInput)).json()).item; touched.add(onlyOrder.id);
    expect((await del(`/api/orders/${onlyOrder.id}`, { version: 1, reason: "E2E 오입력" })).status()).toBe(204);
    expect((await del(`/api/customers/${singleCustomer.id}`, { reason: "과거 이력" })).status()).toBe(409);
    expect((await del(`/api/products/${singleProduct.id}`, { reason: "과거 이력" })).status()).toBe(409);
    expect((await page.request.get("/api/orders/not-a-real-id")).status()).toBe(404);
  } finally {
    // Exact per-run prefix and captured IDs, never actual customer/admin data.
    const orders = await db.query('SELECT id FROM "CustomerOrder" WHERE "customerId" IN (SELECT id FROM "Customer" WHERE code LIKE $1)', [`${prefix}%`]);
    for (const row of orders.rows) touched.add(row.id);
    await db.query('DELETE FROM "Shipment" WHERE "orderId"=ANY($1::text[])', [[...touched]]);
    await db.query('DELETE FROM "CustomerOrder" WHERE id=ANY($1::text[])', [[...touched]]);
    await db.query('DELETE FROM "AuditLog" WHERE "targetId"=ANY($1::text[])', [[...touched]]);
    await db.query('DELETE FROM "Product" WHERE code LIKE $1', [`${prefix}%`]);
    await db.query('DELETE FROM "Customer" WHERE code LIKE $1', [`${prefix}%`]);
    await db.end();
  }
});
